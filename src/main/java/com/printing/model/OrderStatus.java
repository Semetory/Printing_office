package com.printing.model;

/**
 * Перечисление (Enum) доступных состояний/статусов жизненного цикла заказа.
 * <p>
 * Содержит внутреннее связывание системных констант с их официальным, понятным пользователю
 * русскоязычным наименованием для вывода на веб-интерфейсах.
 * </p>
 *
 * @author Дмитрий
 * @version 1.0
 */
public enum OrderStatus {

    /** Заказ успешно зарегистрирован и ожидает начала производства. */
    ACCEPTED("Принят"),

    /** Заказ передан в печатный цех и находится в процессе производства. */
    PRINTING("В печати"),

    /** Производство завершено, продукция ожидает получения на складе/стойке. */
    READY("Готов"),

    /** Продукция успешно передана (отгружена) конечному клиенту. */
    DELIVERED("Выдан");

    /** Текстовое представление статуса на русском языке. */
    private final String rusName;

    /**
     * Конструктор перечисления.
     *
     * @param rusName русскоязычный эквивалент статуса
     */
    OrderStatus(String rusName) {
        this.rusName = rusName;
    }

    /**
     * @return русскоязычное наименование статуса заказа
     */
    public String getRusName() {
        return rusName;
    }
}